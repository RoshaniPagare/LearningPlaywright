//Assignment Operator 
// '=' this is assignment operator
//Assignment operator is used to assign a value to a variable. It stores the value on the right side into the variable on the left side. 
// The most common assignment operator is the equal sign (=).
//Example:
let x = 10;

x = 20; // x is now 20
x = 90;
console.log(x); // Output: 90