//Arithmetic Operator
//Arithmetic operators are used to perform arithmetic operations on numbers (literals or variables).
//The most common arithmetic operators are addition (+), subtraction (-), multiplication (*), division (/), and modulus (%).
//Example:
let a = 10, b = 3;

let sum = a + b;
let subtraction = a - b;
let multiplication = a * b;
let division = a / b;
let modulus = a % b;

console.log("Sum:", sum); // Output: 13
console.log("Subtraction:", subtraction); // Output: 7
console.log("Multiplication:", multiplication); // Output: 30
console.log("Division:", division); // Output: 3
console.log("Modulus:", modulus); // Output: 1