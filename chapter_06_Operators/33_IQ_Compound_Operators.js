//Compound operators are used to perform an operation and assignment in a single step. They combine an arithmetic operation with assignment, making the code more concise and readable.
//Example:
let x = 10;

// Using the addition assignment operator (+=)
x += 5; // Equivalent to x = x + 5
console.log(x); // Output: 15

// Using the subtraction assignment operator (-=)
x -= 3; // Equivalent to x = x - 3
console.log(x); // Output: 12

// Using the multiplication assignment operator (*=)
x *= 2; // Equivalent to x = x * 2
console.log(x); // Output: 24

// Using the division assignment operator (/=)
x /= 4; // Equivalent to x = x / 4
console.log(x); // Output: 6

// Using the modulus assignment operator (%=)
x %= 5; // Equivalent to x = x % 5
console.log(x); // Output: 1    