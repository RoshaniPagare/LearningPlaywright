//preincreament pre++ meaning first increment the value of variable and then use it in expression
//in preincreamnet, the value of the variable is increased by 1 before it is used in an expression.
let a = 10;
let b = ++a; // first increment a to 11, then assign it to b
console.log(a); // 11
console.log(b); // 11


// decreament operator is used to decrease the value of a variable by 1. 
// It can be used in two forms: pre-decrement (--variable) and post-decrement (variable--).

let c = 10;
let d = --c;
console.log(c); // 9
console.log(d); // 9


let e = 10;
let f = e--;
console.log(e); // 9
console.log(f); // 10
