//Modulus Operator
//The modulus operator (%) returns the remainder of a division operation between two numbers. 
//It is often used to determine if a number is even or odd, or to wrap around values within a certain range.
//Example:
let num1 = 13, num2 = 7;

let remainder = num1 % num2;

console.log("Remainder:", remainder); // Output: 6
//any odd number % 2 will return 1, while any even number % 2 will return 0.
console.log(37 % 2); // Output: 1 (37 is odd)
console.log(42 % 2); // Output: 0 (42 is even)

console.log(10 % 3); // Output: 1 (10 divided by 3 leaves a remainder of 1)