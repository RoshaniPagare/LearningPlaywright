//comparision operators will return a boolean value (true or false) based on the comparison between two values. They are used to compare values and determine their relationship.
//comparision operators are as follows:
// 1. Equal to (==)
// 2. Strict equal to (===)
// 3. Not (!)
// 4. Not equal to (!=)
// 5. Strict not equal to (!==)
// 6. Greater than (>)
// 7. Less than (<)
// 8. Greater than or equal to (>=)
// 9. Less than or equal to (<=)

//Example:
let a = 10;
let b = 20;

// Using the equality operator (==)
console.log(a == b); // Output: false

// Using the strict equality operator (===)
console.log(a === b); // Output: false

// Using the inequality operator (!=)
console.log(a != b); // Output: true

// Using the strict inequality operator (!==)
console.log(a !== b); // Output: true

// Using the greater than operator (>)
console.log(a > b); // Output: false

//Using the less than operator (<)
console.log(a < b); // Output: true

//Using greater than or equal to operator (>=)
console.log(a >= b); // Output: true

//Using less than or equal to operator (<=)
console.log(a <= b); // Output: true  