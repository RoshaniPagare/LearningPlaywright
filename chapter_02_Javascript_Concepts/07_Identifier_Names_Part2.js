// lowercase
var name = "Roshani";
console.log(name);

// camelCase
var firstName = "Roshani";
console.log(firstName);

var lastName = "Pagare";
console.log(lastName);

// PascalCase
var FullName = "Roshani Pagare";
console.log(FullName);

// snake_case
var first_name = "Akanksha";
console.log(first_name);

// screaming_snake_case (often used for constants)
var MAX_VALUE = 100;
console.log(MAX_VALUE);

// Hungarian case (type prefix + camelCase)
var strFirstName = "Roshani";
console.log(strFirstName);

// UPPER_CASE (often used for constants)
var MAX_LIMIT = 200;
console.log(MAX_LIMIT);

